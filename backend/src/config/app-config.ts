/**
 * Application configuration, read ONCE from the environment and validated before Nest starts.
 *
 * Rules (owner's security order, audit Q2/Q3):
 *  - no default secret: JWT_SECRET and PRIVATE_KEY_ENCRYPTION_KEY must be set and strong, or the server refuses to start;
 *  - MEV_ENVIRONMENT really chooses the MEV-WEB endpoint;
 *  - PROD is refused unless QCMEV_CERTIFICATION_NUMBER is set, and unless the SEV keys are non-exportable keys in an HSM
 *    (SEV_KEY_CUSTODY=gcp-kms, QCMEV_GCP_KMS_PROTECTION=HSM; see keyCustody);
 *  - the simulator is mounted only in SIMULATOR or DEV, never in ESSAI or PROD;
 *  - the Food Hub integration is OFF unless QCMEV_FOODHUB_ENABLED=true and a secret is set;
 *  - public operator self-registration (POST /api/operators/register) is ON unless QCMEV_PUBLIC_REGISTRATION=false.
 */
import type { LogLevel } from '@nestjs/common';
import type { JwtSignOptions } from '@nestjs/jwt';
import * as crypto from 'crypto';
import * as fs from 'fs';
import { GCP_KEY_RING, type GcpKmsSettings } from '../crypto/gcp-kms';

export type MevEnv = 'SIMULATOR' | 'DEV' | 'ESSAI' | 'PROD';
export const MEV_ENVS: MevEnv[] = ['SIMULATOR', 'DEV', 'ESSAI', 'PROD'];

export interface SevIdentity {
  /** IDSEV, IDVERSI, CODCERTIF, IDPARTN, VERSI, VERSIPARN headers (values assigned by Revenu Québec; SPEC formats). */
  idSev: string;
  idVersi: string;
  codCertif: string;
  idPartn: string;
  versi: string;
  versiParn: string;
}

export interface AppConfig {
  nodeEnv: string;
  port: number;
  logLevels: LogLevel[];
  mevEnvironment: MevEnv;
  /** Value of the ENVIRN header. The local simulator is addressed as DEV. */
  envirnHeader: 'DEV' | 'ESSAI' | 'PROD';
  /** CASESSAI header (test case number), only for ESSAI runs. */
  casEssai: string;
  mevBaseUrl: string;
  mevPaths: { CRT: string; UTL: string; TRX: string; DOC: string };
  mevTimeoutMs: number;
  qrBaseUrl: string;
  simulatorEnabled: boolean;
  simulatorStateDir: string;
  jwtSecret: string;
  jwtExpiresIn: NonNullable<JwtSignOptions['expiresIn']>;
  keyEncryptionKey: Buffer;
  sev: SevIdentity;
  certificationNumber: string;
  certified: boolean;
  /**
   * Where the SEV private keys live (crypto/key-custody.ts). 'software' = generated by Node, sealed AES-256-GCM in the
   * database: exportable by whoever holds PRIVATE_KEY_ENCRYPTION_KEY, so SIMULATOR / DEV / ESSAI only. 'gcp-kms' =
   * generated and kept in Google Cloud KMS, never exported (crypto/gcp-kms.ts): SW-76 (2025-06) §4.2.1 asks a SEV in
   * mode SEV for a non-exportable private key. PROD needs gcp-kms at protection level HSM.
   */
  keyCustody: 'software' | 'gcp-kms';
  /** Google Cloud KMS settings when keyCustody is gcp-kms. */
  gcpKms: GcpKmsSettings | null;
  foodhub: {
    enabled: boolean;
    secrets: string[];
    integrationIds: string[];
    ratePerSecond: number;
  };
  frontendOrigins: string[];
  offlineFlushSeconds: number;
  /** Nightly job (03:00 America/Montreal): SEV certificates expiring within this many days are renewed (CRT REM). */
  certRenewalDays: number;
  /** Simulator only: validity of the certificates it issues (set it low, e.g. 10, to exercise the renewal job). */
  simulatorCertValidityDays: number;
  /** POST /api/operators/register (first-time setup). Product decision: may be turned off once operators are invited. */
  publicRegistration: boolean;
  /** Global rate limit per client IP (per tenant on the Food Hub routes): two tiers. */
  rateLimit: { perSecond: number; perMinute: number };
}

export class ConfigError extends Error {}

const WEAK_MARKERS = ['change', 'secret', 'password', 'example', 'default', 'placeholder', 'takatak', 'xxxx'];

function req(env: NodeJS.ProcessEnv, name: string): string {
  const v = (env[name] ?? '').trim();
  if (!v) throw new ConfigError(`${name} is required`);
  return v;
}

/** A JWT secret must be at least 32 characters, not a known placeholder, and not one repeated character. */
export function assertStrongSecret(name: string, value: string): void {
  if (value.length < 32) throw new ConfigError(`${name} must be at least 32 characters (use: openssl rand -hex 32)`);
  const lower = value.toLowerCase();
  if (WEAK_MARKERS.some((m) => lower.includes(m))) throw new ConfigError(`${name} looks like a placeholder; generate a random value`);
  if (new Set(value).size < 8) throw new ConfigError(`${name} is too repetitive`);
}

/** PRIVATE_KEY_ENCRYPTION_KEY: exactly 32 bytes, given as 64 hex characters or base64. No padding, no truncation. */
export function parseKeyEncryptionKey(raw: string): Buffer {
  const v = raw.trim();
  let key: Buffer | null = null;
  if (/^[0-9a-fA-F]{64}$/.test(v)) key = Buffer.from(v, 'hex');
  else if (/^[A-Za-z0-9+/_-]{43}=?$/.test(v)) key = Buffer.from(v.replace(/-/g, '+').replace(/_/g, '/'), 'base64');
  if (!key || key.length !== 32) {
    throw new ConfigError('PRIVATE_KEY_ENCRYPTION_KEY must be 32 random bytes as 64 hex characters (openssl rand -hex 32) or base64');
  }
  if (new Set(key).size < 8) throw new ConfigError('PRIVATE_KEY_ENCRYPTION_KEY is too repetitive');
  return key;
}

function parseLogLevels(raw: string | undefined): LogLevel[] {
  const order: LogLevel[] = ['error', 'warn', 'log', 'debug', 'verbose'];
  const wanted = (raw ?? 'log').trim().toLowerCase() as LogLevel;
  const idx = order.indexOf(wanted);
  return order.slice(0, idx < 0 ? 3 : idx + 1);
}

function bool(raw: string | undefined, fallback = false): boolean {
  if (raw == null || raw.trim() === '') return fallback;
  return ['1', 'true', 'yes', 'on'].includes(raw.trim().toLowerCase());
}

function positiveInt(env: NodeJS.ProcessEnv, name: string, fallback: number): number {
  const raw = (env[name] ?? '').trim();
  if (!raw) return fallback;
  const n = Number(raw);
  if (!Number.isInteger(n) || n <= 0) throw new ConfigError(`${name} must be a positive integer`);
  return n;
}

function jwtDuration(raw: string | undefined): NonNullable<JwtSignOptions['expiresIn']> {
  const value = raw?.trim() || '8h';
  if (!/^[1-9]\d*(?:ms|s|m|h|d|w|y)$/.test(value)) throw new ConfigError('JWT_EXPIRES_IN must be a positive duration with units, e.g. 8h or 30m');
  return value as NonNullable<JwtSignOptions['expiresIn']>;
}

function nonNegativeInt(env: NodeJS.ProcessEnv, name: string, fallback: number): number {
  if ((env[name] ?? '').trim() === '0') return 0; // documented switch for tests / manual queue processing
  return positiveInt(env, name, fallback);
}

function list(raw: string | undefined): string[] {
  return (raw ?? '').split(',').map((s) => s.trim()).filter(Boolean);
}

/**
 * SEV_KEY_CUSTODY=gcp-kms: the key ring, the protection level and the service account (file path or JSON, never in git).
 * The endpoints are https; a local http test server (fake KMS) is accepted only in SIMULATOR / DEV.
 */
function parseGcpKms(env: NodeJS.ProcessEnv, mevEnvironment: MevEnv): GcpKmsSettings {
  const keyRing = req(env, 'QCMEV_GCP_KMS_KEY_RING');
  if (!GCP_KEY_RING.test(keyRing)) throw new ConfigError('QCMEV_GCP_KMS_KEY_RING must be projects/<project>/locations/<region>/keyRings/<ring>');
  const protectionLevel = (env.QCMEV_GCP_KMS_PROTECTION ?? 'HSM').trim().toUpperCase();
  if (protectionLevel !== 'HSM' && protectionLevel !== 'SOFTWARE') throw new ConfigError('QCMEV_GCP_KMS_PROTECTION must be HSM or SOFTWARE');
  const file = (env.QCMEV_GCP_KMS_CREDENTIALS_FILE ?? '').trim();
  const inline = (env.QCMEV_GCP_KMS_CREDENTIALS_JSON ?? '').trim();
  if (!file === !inline) throw new ConfigError('Set exactly one of QCMEV_GCP_KMS_CREDENTIALS_FILE or QCMEV_GCP_KMS_CREDENTIALS_JSON (the KMS service account key)');
  let raw: string;
  try {
    raw = inline || fs.readFileSync(file, 'utf8');
  } catch {
    throw new ConfigError('QCMEV_GCP_KMS_CREDENTIALS_FILE cannot be read');
  }
  let sa: { type?: string; client_email?: string; private_key?: string; token_uri?: string } | null = null;
  try {
    sa = JSON.parse(raw);
  } catch {
    /* reported below */
  }
  if (sa?.type !== 'service_account' || !sa.client_email || !sa.private_key) {
    throw new ConfigError('The KMS credentials must be a Google service account key (type, client_email, private_key)');
  }
  try {
    crypto.createPrivateKey(sa.private_key);
  } catch {
    throw new ConfigError('The KMS service account private_key is not a valid key');
  }
  const tokenUri = (sa.token_uri ?? '').trim() || 'https://oauth2.googleapis.com/token';
  const endpoint = (env.QCMEV_GCP_KMS_ENDPOINT ?? '').trim().replace(/\/+$/, '') || 'https://cloudkms.googleapis.com';
  const localTest = (u: string) => /^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?(\/|$)/.test(u) && (mevEnvironment === 'SIMULATOR' || mevEnvironment === 'DEV');
  for (const [name, url] of [['QCMEV_GCP_KMS_ENDPOINT', endpoint], ['token_uri', tokenUri]] as const) {
    if (!/^https:\/\/[a-z0-9.-]+(:\d+)?(\/|$)/i.test(url) && !localTest(url)) throw new ConfigError(`${name} must be an https:// URL (a local http test server only in SIMULATOR / DEV)`);
  }
  return { keyRing, protectionLevel, credentials: { clientEmail: sa.client_email, privateKey: sa.private_key, tokenUri }, endpoint };
}

export function loadConfig(env: NodeJS.ProcessEnv = process.env): AppConfig {
  const port = positiveInt(env, 'PORT', 3001);
  if (port > 65535) throw new ConfigError('PORT must not exceed 65535');

  const mevEnvironment = (env.MEV_ENVIRONMENT ?? 'SIMULATOR').trim().toUpperCase() as MevEnv;
  if (!MEV_ENVS.includes(mevEnvironment)) {
    throw new ConfigError(`MEV_ENVIRONMENT must be one of ${MEV_ENVS.join(', ')} (got "${env.MEV_ENVIRONMENT}")`);
  }

  const jwtSecret = req(env, 'JWT_SECRET');
  assertStrongSecret('JWT_SECRET', jwtSecret);
  const keyEncryptionKey = parseKeyEncryptionKey(req(env, 'PRIVATE_KEY_ENCRYPTION_KEY'));

  const certificationNumber = (env.QCMEV_CERTIFICATION_NUMBER ?? '').trim();
  if (mevEnvironment === 'PROD' && !certificationNumber) {
    throw new ConfigError('MEV_ENVIRONMENT=PROD is refused: QCMEV_CERTIFICATION_NUMBER is not set (the product is not certified)');
  }

  const keyCustody = (env.SEV_KEY_CUSTODY ?? 'software').trim().toLowerCase();
  if (keyCustody !== 'software' && keyCustody !== 'gcp-kms') throw new ConfigError(`SEV_KEY_CUSTODY must be software or gcp-kms (got "${keyCustody}")`);
  const gcpKms = keyCustody === 'gcp-kms' ? parseGcpKms(env, mevEnvironment) : null;
  if (mevEnvironment === 'PROD' && gcpKms?.protectionLevel !== 'HSM') {
    throw new ConfigError('MEV_ENVIRONMENT=PROD is refused: SW-76 §4.2.1 requires a non-exportable SEV private key — set SEV_KEY_CUSTODY=gcp-kms with QCMEV_GCP_KMS_PROTECTION=HSM (docs/revenu-quebec/KEY_CUSTODY.md)');
  }

  const simulatorEnabled = (mevEnvironment === 'SIMULATOR' || mevEnvironment === 'DEV') && bool(env.MEV_SIMULATOR_ENABLED, true);
  const localSim = `http://127.0.0.1:${port}/api/mev-simulator`;

  let mevBaseUrl: string;
  if (mevEnvironment === 'SIMULATOR') {
    mevBaseUrl = (env.SIMULATOR_URL ?? '').trim() || localSim;
  } else {
    // SPEC: the official DEV / ESSAI / PROD URLs come with the partner documents (SW-73). No guessed URL is built in.
    mevBaseUrl = req(env, 'MEV_WEB_BASE_URL');
    if (!/^https:\/\//.test(mevBaseUrl)) throw new ConfigError('MEV_WEB_BASE_URL must be an https:// URL outside the simulator');
  }
  mevBaseUrl = mevBaseUrl.replace(/\/+$/, '');

  const sevDefaults: SevIdentity = {
    idSev: 'SIM-IDSEV', idVersi: 'SIM-IDVERSI', codCertif: 'SIM-CODCERTIF', idPartn: 'SIM-IDPARTN', versi: '0.2.0', versiParn: '0',
  };
  const sev: SevIdentity = {
    idSev: env.MEV_IDSEV?.trim() || '',
    idVersi: env.MEV_IDVERSI?.trim() || '',
    codCertif: env.MEV_CODCERTIF?.trim() || certificationNumber || '',
    idPartn: env.MEV_IDPARTN?.trim() || '',
    versi: env.MEV_VERSI?.trim() || '',
    versiParn: env.MEV_VERSIPARN?.trim() || '',
  };
  for (const k of Object.keys(sev) as (keyof SevIdentity)[]) {
    if (!sev[k]) {
      if (mevEnvironment === 'SIMULATOR') sev[k] = sevDefaults[k];
      else throw new ConfigError(`MEV_${k.toUpperCase()} is required outside the simulator (value given by Revenu Québec)`);
    }
  }

  const qrBaseUrl = (env.MEV_QR_BASE_URL ?? '').trim() || (mevEnvironment === 'SIMULATOR' ? `${localSim}/qr` : '');
  if (!qrBaseUrl) throw new ConfigError('MEV_QR_BASE_URL is required outside the simulator (SPEC: QR format from SW-73)');
  if (mevEnvironment === 'SIMULATOR' && /revenuquebec\.ca|mev-web\.ca/i.test(qrBaseUrl)) {
    throw new ConfigError('The simulator never points QR codes at a Revenu Québec domain');
  }

  const secrets = [env.QCMEV_FOODHUB_SECRET, env.QCMEV_FOODHUB_SECRET_PREVIOUS].map((s) => (s ?? '').trim()).filter(Boolean);
  const foodhubEnabled = bool(env.QCMEV_FOODHUB_ENABLED, false);
  if (foodhubEnabled) {
    if (!secrets.length) throw new ConfigError('QCMEV_FOODHUB_ENABLED=true needs QCMEV_FOODHUB_SECRET');
    secrets.forEach((s, i) => assertStrongSecret(i === 0 ? 'QCMEV_FOODHUB_SECRET' : 'QCMEV_FOODHUB_SECRET_PREVIOUS', s));
  }

  const envirnHeader: AppConfig['envirnHeader'] = mevEnvironment === 'SIMULATOR' ? 'DEV' : mevEnvironment;

  return {
    nodeEnv: env.NODE_ENV ?? 'development',
    port,
    logLevels: parseLogLevels(env.LOG_LEVEL),
    mevEnvironment,
    envirnHeader,
    casEssai: (env.MEV_CASESSAI ?? '').trim() || '000.000',
    mevBaseUrl,
    mevPaths: {
      // SPEC: path names from the 2022 sample code; confirm in SW-73.
      CRT: env.MEV_PATH_CRT?.trim() || '/enrolement',
      UTL: env.MEV_PATH_UTL?.trim() || '/utilisateur',
      TRX: env.MEV_PATH_TRX?.trim() || '/transaction',
      DOC: env.MEV_PATH_DOC?.trim() || '/document',
    },
    mevTimeoutMs: positiveInt(env, 'MEV_TIMEOUT_MS', 10000),
    qrBaseUrl,
    simulatorEnabled,
    simulatorStateDir: (env.MEV_SIMULATOR_STATE_DIR ?? '').trim(),
    jwtSecret,
    jwtExpiresIn: jwtDuration(env.JWT_EXPIRES_IN),
    keyEncryptionKey,
    sev,
    certificationNumber,
    certified: (mevEnvironment as MevEnv) === 'PROD' && !!certificationNumber,
    keyCustody: keyCustody as AppConfig['keyCustody'],
    gcpKms,
    foodhub: {
      enabled: foodhubEnabled,
      secrets,
      integrationIds: list(env.QCMEV_FOODHUB_INTEGRATION_IDS).length ? list(env.QCMEV_FOODHUB_INTEGRATION_IDS) : ['foodhub', 'on2go_hub'],
      ratePerSecond: positiveInt(env, 'QCMEV_FOODHUB_RATE_PER_SECOND', 20),
    },
    frontendOrigins: list(env.FRONTEND_URL).length ? list(env.FRONTEND_URL) : ['http://localhost:3000'],
    offlineFlushSeconds: nonNegativeInt(env, 'MEV_OFFLINE_FLUSH_SECONDS', 30),
    certRenewalDays: positiveInt(env, 'CERT_RENEWAL_DAYS', 30),
    simulatorCertValidityDays: positiveInt(env, 'SIMULATOR_CERT_VALIDITY_DAYS', 730),
    publicRegistration: bool(env.QCMEV_PUBLIC_REGISTRATION, true),
    rateLimit: {
      perSecond: positiveInt(env, 'QCMEV_RATE_LIMIT_PER_SECOND', 10),
      perMinute: positiveInt(env, 'QCMEV_RATE_LIMIT_PER_MINUTE', 100),
    },
  };
}

